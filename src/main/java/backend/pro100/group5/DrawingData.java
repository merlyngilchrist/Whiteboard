package backend.pro100.group5;

public class DrawingData {

    private int x;
    private int y;
    private String action;
    private String color;
    private int tool;
    private int size;

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }

    public String getAction() {
        return action;
    }

    public String getColor() {
        return color;
    }

    public int getTool() {
        return tool;
    }

    public int getSize() {
        return size;
    }

}
